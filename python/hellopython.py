### 파이참 기본 단축키

# Shift + F10 : 코드 실행
# Ctrl + D : 줄 복사
# Shift + Del : 줄 삭제
# Ctrl + / : 주석 설정/해제
# Ctrl + F : 코드 검색 (해제는 ESC)
# Ctrl + 왼/오른쪽 방향키 : 워드 단위 커서 이동
# Ctrl + Shift + 왼/오른쪽 방향키 : 워드 단위 블럭 지정
# Ctrl + 상/하 방향키 : 커서 고정 상태에서 화면 스크롤

# 문자열을 화면에 출력
